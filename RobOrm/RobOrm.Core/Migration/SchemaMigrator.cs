using System;
using System.Linq;

using RobOrm.Core.EntityGeneration;
using RobOrm.Core.Internal;
using RobOrm.Core.Query.Model;

namespace RobOrm.Core.Migration
{
    public class SchemaMigrator : ISchemaMigrator
    {
        private readonly IDataModelHelper _dataModel;
        private readonly IEntityNamingConvention _convention;
        private readonly IEntityCollector _entityCollector;

        public SchemaMigrator(IDataModelHelper dataModel, IEntityNamingConvention convention, IEntityCollector entityCollector)
        {
            _dataModel = dataModel;
            _convention = convention;
            _entityCollector = entityCollector;
        }

        public void MigrateStructure(IMigrationScriptBuilder script)
        {
            if (_entityCollector == null)
            {
                throw new InvalidOperationException($"{typeof(IEntityCollector)} is not provided");
            }

            var entities = _entityCollector.GetEntityTypes().ToList();

            foreach (var entity in entities)
            {
                var table = _dataModel.GetTableName(entity);

                var pk = _convention.GetPrimaryKeyProperty(entity);

                script.CreateTable(
                    table,
                    _dataModel.GetColumnName(pk),
                    pk.PropertyType,
                    PkHandlingHelper.IsPkAutogenerated(pk));

                var relations = _dataModel.GetReferences(entity).ToList();

                var columns = _dataModel.GetTableDataColumns(entity);
                foreach (var column in columns)
                {
                    try
                    {
                        if (column == pk) continue;

                        var type = SqlTypeMapper.GetColumnType(column);
                        var columnName = _convention.GetColumnName(column);
                        script.CreateColumn(table, columnName, type.ColumnDeclarationTypeText, type.IsNullable, false);

                        var references =
                            relations.Where(r => (r.LeftEntityType == entity) && (r.LeftKeyColumnName == columnName));

                        foreach (var relation in references)
                        {
                            script.CreateForeignKey(
                                table,
                                columnName,
                                _dataModel.GetTableName(relation.RightEntityType),
                                relation.RightKeyColumnName);
                        }
                    }
                    catch (Exception ex)
                    {
                        throw new InvalidOperationException($"Schema migration failed, table={table}, column={column}", ex);
                    }
                }
            }
        }
    }
}
