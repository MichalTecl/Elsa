using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Linq;

using Newtonsoft.Json;

using RobOrm.Core.EntityModel;

namespace RobOrm.Core.EntityGeneration
{
    /// <summary>
    /// Base class of the runtime generated entity implementations. The generated class adds only the backing fields
    /// and properties of the entity interface; the <see cref="IEntity"/> logic lives here.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public abstract class EntityBase : IEntity
    {
        private readonly EntityTypeInfo _typeInfo;
        private readonly IEntitySet[] _references;

        protected EntityBase(EntityTypeInfo typeInfo)
        {
            if (typeInfo == null)
            {
                throw new ArgumentNullException(nameof(typeInfo));
            }

            _typeInfo = typeInfo;

            var references = typeInfo.References;
            _references = new IEntitySet[references.Count];
            for (var i = 0; i < references.Count; i++)
            {
                _references[i] = references[i].IsCollection ? (IEntitySet)new EntityList() : new EntityHolder();
            }

            IsDirty = true;
        }

        [JsonIgnore]
        public string DbEntityName => _typeInfo.DbEntityName;

        [JsonIgnore]
        public bool IsDirty { get; set; }

        [JsonIgnore]
        public object PrimaryKeyValue
        {
            get
            {
                return _typeInfo.Accessors.GetPrimaryKey(this);
            }

            set
            {
                _typeInfo.Accessors.SetPrimaryKey(this, value);
            }
        }

        [JsonIgnore]
        public Type PrimaryKeyType => _typeInfo.PrimaryKeyType;

        [JsonIgnore]
        public bool IsPrimaryKeyAutogenerated => _typeInfo.IsPrimaryKeyAutogenerated;

        public void ReadSelf(IDataRecord row)
        {
            if (!ReadPrimaryKey(row))
            {
                return;
            }

            _typeInfo.Accessors.ReadColumns(this, row);
        }

        public bool ReadPrimaryKey(IDataRecord reader)
        {
            if (reader.IsNull(_typeInfo.PrimaryKeyName))
            {
                return false;
            }

            _typeInfo.Accessors.ReadPrimaryKey(this, reader);

            return true;
        }

        public IEnumerable<Tuple<string, Type>> GetReferenceProperties()
        {
            foreach (var reference in _typeInfo.ReferenceTuples)
            {
                yield return reference;
            }
        }

        public IEntitySet OpenProperty(string propertyName)
        {
            var references = _typeInfo.References;
            for (var i = 0; i < references.Count; i++)
            {
                if (references[i].Name == propertyName)
                {
                    return _references[i];
                }
            }

            throw new InvalidOperationException("Unknown property requested");
        }

        public SaveMethodType GetSaveMethodType()
        {
            if (!_typeInfo.IsPrimaryKeyAutogenerated)
            {
                return SaveMethodType.Merge;
            }

            return _typeInfo.Accessors.IsPrimaryKeyDefault(this) ? SaveMethodType.Insert : SaveMethodType.Update;
        }

        public IEnumerable<EntityColumnValue> GetValues()
        {
            var accessors = _typeInfo.Accessors;

            yield return new EntityColumnValue(_typeInfo.PrimaryKeyName, true, accessors.GetPrimaryKey(this));

            var columns = _typeInfo.Columns;
            var values = accessors.GetColumnValues(this);

            for (var i = 0; i < columns.Count; i++)
            {
                yield return new EntityColumnValue(columns[i].Name, false, values[i]);
            }
        }

        /// <summary>
        /// Used by generated getters of single entity references.
        /// </summary>
        protected TEntity GetSingleReference<TEntity>(int index) where TEntity : class
        {
            return ((EntityHolder)_references[index]).Value as TEntity;
        }

        /// <summary>
        /// Used by generated getters of entity collection references.
        /// </summary>
        protected IEnumerable<TEntity> GetReferenceCollection<TEntity>(int index)
        {
            return _references[index].OfType<TEntity>();
        }
    }
}
