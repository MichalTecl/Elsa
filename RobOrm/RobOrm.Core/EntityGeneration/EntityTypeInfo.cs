using System;
using System.Collections;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;

using RobOrm.Core.Internal;

namespace RobOrm.Core.EntityGeneration
{
    /// <summary>
    /// Description of an entity interface and of its runtime generated implementation.
    /// </summary>
    public sealed class EntityTypeInfo
    {
        private readonly Lazy<EntityAccessors> _accessors;

        private EntityTypeInfo(
            Type entityType,
            string dbEntityName,
            PropertyInfo primaryKeyProperty,
            bool isPrimaryKeyAutogenerated,
            List<EntityPropertyInfo> properties,
            List<EntityReferenceInfo> references)
        {
            EntityType = entityType;
            DbEntityName = dbEntityName;
            PrimaryKeyProperty = primaryKeyProperty;
            IsPrimaryKeyAutogenerated = isPrimaryKeyAutogenerated;
            Properties = properties;
            Columns = properties.Where(p => p.IsColumn).ToList();
            References = references;
            ReferenceTuples = references.Select(r => new Tuple<string, Type>(r.Name, r.EntityType)).ToArray();

            _accessors = new Lazy<EntityAccessors>(() => EntityAccessors.Compile(this));
        }

        /// <summary>
        /// The entity interface.
        /// </summary>
        public Type EntityType { get; }

        /// <summary>
        /// The generated class implementing <see cref="EntityType"/>.
        /// </summary>
        public Type ImplementationType { get; internal set; }

        public string DbEntityName { get; }

        public PropertyInfo PrimaryKeyProperty { get; }

        public string PrimaryKeyName => PrimaryKeyProperty.Name;

        public Type PrimaryKeyType => PrimaryKeyProperty.PropertyType;

        public bool IsPrimaryKeyAutogenerated { get; }

        /// <summary>
        /// Column and plain properties (everything except the primary key and references) in declaration order.
        /// </summary>
        internal IReadOnlyList<EntityPropertyInfo> Properties { get; }

        /// <summary>
        /// Column properties (except the primary key) in declaration order.
        /// </summary>
        internal IReadOnlyList<EntityPropertyInfo> Columns { get; }

        internal IReadOnlyList<EntityReferenceInfo> References { get; }

        internal Tuple<string, Type>[] ReferenceTuples { get; }

        internal EntityAccessors Accessors => _accessors.Value;

        internal object CreateInstance()
        {
            return Accessors.Create();
        }

        /// <summary>
        /// Reads the entity interface and validates it. The rules and error messages are the same as in the former Robowire based generator.
        /// </summary>
        internal static EntityTypeInfo Build(Type entityType, IEntityNamingConvention convention)
        {
            if (!entityType.IsInterface)
            {
                throw new InvalidOperationException($"{entityType.FullName} is marked with {nameof(EntityAttribute)}, but only interfaces can be entities");
            }

            if (!entityType.IsVisible)
            {
                throw new InvalidOperationException($"Entity interface {entityType.FullName} must be public");
            }

            var entityAttribute = Attribute.GetCustomAttribute(entityType, typeof(EntityAttribute)) as EntityAttribute;

            var primaryKeyName = entityAttribute?.PrimaryKeyProperty;
            if (string.IsNullOrWhiteSpace(primaryKeyName))
            {
                primaryKeyName = "Id";
            }

            var primaryKeyProperty = ReflectionUtil.GetProperty(entityType, primaryKeyName);
            if (primaryKeyProperty == null)
            {
                throw new InvalidOperationException($"{entityType.Name} - Primary Key property \"{primaryKeyName}\" not found");
            }

            var properties = CollectProperties(entityType, primaryKeyName, convention);

            var isPrimaryKeyAutogenerated = PkHandlingHelper.IsPkAutogenerated(primaryKeyProperty);

            var references = CollectReferences(entityType, convention);

            return new EntityTypeInfo(
                entityType,
                NamingHelper.GetEntityName(entityType),
                primaryKeyProperty,
                isPrimaryKeyAutogenerated,
                properties,
                references);
        }

        private static List<EntityPropertyInfo> CollectProperties(Type entityType, string primaryKeyName, IEntityNamingConvention convention)
        {
            var result = new List<EntityPropertyInfo>();
            var names = new HashSet<string>(StringComparer.Ordinal);

            foreach (var sourceProperty in ReflectionUtil.GetAllProperties(entityType))
            {
                if (sourceProperty.Name == primaryKeyName)
                {
                    continue;
                }

                if (!sourceProperty.CanRead)
                {
                    continue;
                }

                try
                {
                    if (string.IsNullOrWhiteSpace(convention.GetColumnName(sourceProperty)))
                    {
                        if ((convention.TryGetRefEntityType(sourceProperty) == null) && names.Add(sourceProperty.Name))
                        {
                            result.Add(new EntityPropertyInfo(sourceProperty, false));
                        }

                        continue;
                    }

                    if (!sourceProperty.CanWrite)
                    {
                        throw new InvalidOperationException(
                                  $"Property {sourceProperty.DeclaringType?.Name}.{sourceProperty.Name} seems to be a column, but has no setter");
                    }

                    if ((sourceProperty.Name.Length > 2) && sourceProperty.Name.EndsWith("Id") && !Attribute.IsDefined(sourceProperty, typeof(NotFkAttribute)))
                    {
                        var typedPropName = sourceProperty.Name.Substring(0, sourceProperty.Name.Length - 2);

                        var typedProp = ReflectionUtil.GetProperty(entityType, typedPropName);
                        if ((typedProp == null)
                            || (convention.TryGetRefEntityType(typedProp) == null))
                        {
                            throw new InvalidOperationException($"Property {sourceProperty.DeclaringType}.{sourceProperty.Name} seems to be a foreign key, but there is not any property {typedPropName} of Entity type to describe the reference. Add {typedPropName} or mark the property with {typeof(NotFkAttribute)}");
                        }
                    }

                    if (names.Add(sourceProperty.Name))
                    {
                        result.Add(new EntityPropertyInfo(sourceProperty, true));
                    }
                }
                catch (Exception ex)
                {
                    throw new InvalidOperationException($"Failed to map property {sourceProperty.DeclaringType}.{sourceProperty.Name}", ex);
                }
            }

            return result;
        }

        private static List<EntityReferenceInfo> CollectReferences(Type entityType, IEntityNamingConvention convention)
        {
            var result = new List<EntityReferenceInfo>();
            var names = new HashSet<string>(StringComparer.Ordinal);

            foreach (var property in ReflectionUtil.GetAllProperties(entityType))
            {
                var foreignEntityType = convention.TryGetRefEntityType(property);
                if (foreignEntityType == null)
                {
                    continue;
                }

                if (!names.Add(property.Name))
                {
                    continue;
                }

                var isCollection = typeof(IEnumerable).IsAssignableFrom(property.PropertyType);

                result.Add(new EntityReferenceInfo(property, foreignEntityType, isCollection, result.Count));
            }

            return result;
        }
    }

    internal sealed class EntityPropertyInfo
    {
        public EntityPropertyInfo(PropertyInfo source, bool isColumn)
        {
            Source = source;
            IsColumn = isColumn;
        }

        public PropertyInfo Source { get; }

        public string Name => Source.Name;

        public Type PropertyType => Source.PropertyType;

        /// <summary>
        /// Column properties set the IsDirty flag when changed and are read/written from/to the database.
        /// </summary>
        public bool IsColumn { get; }
    }

    internal sealed class EntityReferenceInfo
    {
        public EntityReferenceInfo(PropertyInfo source, Type entityType, bool isCollection, int index)
        {
            Source = source;
            EntityType = entityType;
            IsCollection = isCollection;
            Index = index;
        }

        public PropertyInfo Source { get; }

        public string Name => Source.Name;

        public Type PropertyType => Source.PropertyType;

        /// <summary>
        /// Type of the referenced entity (item type for collections).
        /// </summary>
        public Type EntityType { get; }

        public bool IsCollection { get; }

        public int Index { get; }
    }
}
