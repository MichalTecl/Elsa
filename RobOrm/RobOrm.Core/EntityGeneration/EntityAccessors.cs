using System;
using System.Collections.Generic;
using System.Linq;
using System.Linq.Expressions;
using System.Reflection;

namespace RobOrm.Core.EntityGeneration
{
    /// <summary>
    /// Compiled delegates working with the generated entity class. Compiled lazily on the first use of the entity type.
    /// </summary>
    internal sealed class EntityAccessors
    {
        private static readonly MethodInfo s_isNullMethod = typeof(IDataRecord).GetMethod(nameof(IDataRecord.IsNull), new[] { typeof(string) });

        private static readonly MethodInfo s_getByNameMethod = typeof(IDataRecord)
            .GetMethods()
            .Single(
                m => (m.Name == nameof(IDataRecord.Get))
                     && m.IsGenericMethodDefinition
                     && (m.GetParameters().Length == 1)
                     && (m.GetParameters()[0].ParameterType == typeof(string)));

        public Func<object> Create { get; private set; }

        /// <summary>
        /// Assigns the primary key from the record (without checking for NULL).
        /// </summary>
        public Action<object, IDataRecord> ReadPrimaryKey { get; private set; }

        /// <summary>
        /// Assigns all column properties from the record (NULL -> default value).
        /// </summary>
        public Action<object, IDataRecord> ReadColumns { get; private set; }

        public Func<object, object> GetPrimaryKey { get; private set; }

        public Action<object, object> SetPrimaryKey { get; private set; }

        /// <summary>
        /// Values of <see cref="EntityTypeInfo.Columns"/> in the same order.
        /// </summary>
        public Func<object, object[]> GetColumnValues { get; private set; }

        /// <summary>
        /// Only for entities with autogenerated primary key; null otherwise.
        /// </summary>
        public Func<object, bool> IsPrimaryKeyDefault { get; private set; }

        public static EntityAccessors Compile(EntityTypeInfo info)
        {
            var implType = info.ImplementationType;
            if (implType == null)
            {
                throw new InvalidOperationException($"Implementation of entity {info.EntityType} has not been generated");
            }

            var entityParam = Expression.Parameter(typeof(object), "entity");
            var recordParam = Expression.Parameter(typeof(IDataRecord), "record");
            var valueParam = Expression.Parameter(typeof(object), "value");
            var typedEntity = Expression.Variable(implType, "typed");

            Func<string, PropertyInfo> implProperty = name =>
                {
                    var prop = implType.GetProperty(name, BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly);
                    if (prop == null)
                    {
                        throw new InvalidOperationException($"Generated entity {implType} has no property {name}");
                    }

                    return prop;
                };

            var pkProperty = implProperty(info.PrimaryKeyName);
            var pkType = pkProperty.PropertyType;

            var result = new EntityAccessors();

            // new TImpl()
            result.Create = Expression.Lambda<Func<object>>(Expression.Convert(Expression.New(implType), typeof(object))).Compile();

            // ((TImpl)entity).Pk = record.Get<TPk>("Pk")
            result.ReadPrimaryKey = Expression.Lambda<Action<object, IDataRecord>>(
                Expression.Assign(
                    Expression.Property(Expression.Convert(entityParam, implType), pkProperty),
                    Expression.Call(recordParam, s_getByNameMethod.MakeGenericMethod(pkType), Expression.Constant(info.PrimaryKeyName))),
                entityParam,
                recordParam).Compile();

            // foreach column: if (!record.IsNull("C")) typed.C = record.Get<T>("C"); else typed.C = default(T);
            var readStatements = new List<Expression> { Expression.Assign(typedEntity, Expression.Convert(entityParam, implType)) };
            foreach (var column in info.Columns)
            {
                var prop = implProperty(column.Name);
                var columnName = Expression.Constant(column.Name);

                readStatements.Add(
                    Expression.IfThenElse(
                        Expression.Not(Expression.Call(recordParam, s_isNullMethod, columnName)),
                        Expression.Assign(Expression.Property(typedEntity, prop), Expression.Call(recordParam, s_getByNameMethod.MakeGenericMethod(prop.PropertyType), columnName)),
                        Expression.Assign(Expression.Property(typedEntity, prop), Expression.Default(prop.PropertyType))));
            }

            readStatements.Add(Expression.Empty());

            result.ReadColumns = Expression.Lambda<Action<object, IDataRecord>>(
                Expression.Block(new[] { typedEntity }, readStatements),
                entityParam,
                recordParam).Compile();

            // (object)((TImpl)entity).Pk
            result.GetPrimaryKey = Expression.Lambda<Func<object, object>>(
                Expression.Convert(Expression.Property(Expression.Convert(entityParam, implType), pkProperty), typeof(object)),
                entityParam).Compile();

            // ((TImpl)entity).Pk = (TPk)value
            result.SetPrimaryKey = Expression.Lambda<Action<object, object>>(
                Expression.Assign(Expression.Property(Expression.Convert(entityParam, implType), pkProperty), Expression.Convert(valueParam, pkType)),
                entityParam,
                valueParam).Compile();

            // new object[] { (object)typed.C1, (object)typed.C2, ... }
            result.GetColumnValues = Expression.Lambda<Func<object, object[]>>(
                Expression.Block(
                    new[] { typedEntity },
                    Expression.Assign(typedEntity, Expression.Convert(entityParam, implType)),
                    Expression.NewArrayInit(
                        typeof(object),
                        info.Columns.Select(c => (Expression)Expression.Convert(Expression.Property(typedEntity, implProperty(c.Name)), typeof(object))))),
                entityParam).Compile();

            if (info.IsPrimaryKeyAutogenerated)
            {
                // ((TImpl)entity).Pk == default(TPk)
                result.IsPrimaryKeyDefault = Expression.Lambda<Func<object, bool>>(
                    Expression.Equal(Expression.Property(Expression.Convert(entityParam, implType), pkProperty), Expression.Default(pkType)),
                    entityParam).Compile();
            }

            return result;
        }
    }
}
