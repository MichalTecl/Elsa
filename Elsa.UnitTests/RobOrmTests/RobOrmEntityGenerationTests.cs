using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;

using Newtonsoft.Json;

using RobOrm.Core;
using RobOrm.Core.EntityGeneration;
using RobOrm.Core.EntityModel;

using Robowire;

using Xunit;

namespace Elsa.UnitTests.RobOrmTests
{
    /// <summary>
    /// Compares the runtime generated entities (RobOrm.Core.EntityGeneration) with the former Robowire generated ones
    /// (<see cref="LegacyEntityGenerator"/>) for every entity in the Elsa assemblies referenced by this project.
    /// </summary>
    public class RobOrmEntityGenerationTests
    {
        private static readonly HashSet<string> s_entityInterfaceMembers = new HashSet<string>(typeof(IEntity).GetProperties().Select(p => p.Name));

        private static readonly Lazy<Fixture> s_fixture = new Lazy<Fixture>(() => new Fixture());

        public static IEnumerable<object[]> EntityTypes => Fixture.FindEntityTypes().Select(t => new object[] { t });

        [Fact]
        public void EntitiesAreFound()
        {
            Assert.True(s_fixture.Value.EntityTypes.Count > 50, $"Only {s_fixture.Value.EntityTypes.Count} entities found");
            Assert.Equal(s_fixture.Value.EntityTypes.Count, s_fixture.Value.Registry.Count);
        }

        [Theory]
        [MemberData(nameof(EntityTypes))]
        public void MetadataMatches(Type entityType)
        {
            var legacy = s_fixture.Value.CreateLegacy(entityType);
            var modern = s_fixture.Value.CreateModern(entityType);

            Assert.IsAssignableFrom(entityType, modern);
            Assert.Equal(legacy.DbEntityName, modern.DbEntityName);
            Assert.Equal(legacy.PrimaryKeyType, modern.PrimaryKeyType);
            Assert.Equal(legacy.IsPrimaryKeyAutogenerated, modern.IsPrimaryKeyAutogenerated);
            Assert.Equal(legacy.IsDirty, modern.IsDirty);
            Assert.Equal(legacy.GetSaveMethodType(), modern.GetSaveMethodType());
            Assert.Equal(legacy.PrimaryKeyValue, modern.PrimaryKeyValue);

            Assert.Equal(
                legacy.GetReferenceProperties().Select(r => $"{r.Item1}:{r.Item2.FullName}").ToList(),
                modern.GetReferenceProperties().Select(r => $"{r.Item1}:{r.Item2.FullName}").ToList());

            foreach (var reference in legacy.GetReferenceProperties())
            {
                Assert.Equal(legacy.OpenProperty(reference.Item1).GetType(), modern.OpenProperty(reference.Item1).GetType());
            }

            Assert.Throws<InvalidOperationException>(() => legacy.OpenProperty("__unknown__"));
            Assert.Throws<InvalidOperationException>(() => modern.OpenProperty("__unknown__"));
        }

        [Theory]
        [MemberData(nameof(EntityTypes))]
        public void PublicPropertiesMatch(Type entityType)
        {
            var legacy = s_fixture.Value.CreateLegacy(entityType);
            var modern = s_fixture.Value.CreateModern(entityType);

            Assert.Equal(DescribeProperties(legacy.GetType()), DescribeProperties(modern.GetType()));
        }

        [Theory]
        [MemberData(nameof(EntityTypes))]
        public void FilledEntitiesMatch(Type entityType)
        {
            var legacy = s_fixture.Value.CreateLegacy(entityType);
            var modern = s_fixture.Value.CreateModern(entityType);

            Assert.Equal(Serialize(legacy), Serialize(modern));
            AssertValuesEqual(legacy, modern);

            legacy.PrimaryKeyValue = legacy.PrimaryKeyValue;
            modern.PrimaryKeyValue = modern.PrimaryKeyValue;

            SetIsDirty(legacy, false);
            SetIsDirty(modern, false);

            Fill(legacy);
            Fill(modern);

            Assert.Equal(legacy.IsDirty, modern.IsDirty);
            Assert.Equal(legacy.GetSaveMethodType(), modern.GetSaveMethodType());
            Assert.Equal(legacy.PrimaryKeyValue, modern.PrimaryKeyValue);
            Assert.Equal(Serialize(legacy), Serialize(modern));
            AssertValuesEqual(legacy, modern);

            // Setting the same values again (equality semantics of the setters)
            SetIsDirty(legacy, false);
            SetIsDirty(modern, false);

            Fill(legacy);
            Fill(modern);

            Assert.Equal(legacy.IsDirty, modern.IsDirty);
        }

        [Theory]
        [MemberData(nameof(EntityTypes))]
        public void ReadingFromRecordMatches(Type entityType)
        {
            var source = s_fixture.Value.CreateLegacy(entityType);
            Fill(source);

            var values = source.GetValues().ToList();

            // Full record
            var record = new FakeDataRecord(values.ToDictionary(v => v.ColumnName, v => v.Value));
            AssertReadMatches(entityType, record);

            // Record with NULLs in all columns except the primary key
            var nullRecord = new FakeDataRecord(values.ToDictionary(v => v.ColumnName, v => v.IsPk ? v.Value : null));
            AssertReadMatches(entityType, nullRecord);

            // Record without the primary key
            var noPkRecord = new FakeDataRecord(values.Where(v => !v.IsPk).ToDictionary(v => v.ColumnName, v => v.Value));
            var legacy = s_fixture.Value.CreateLegacy(entityType);
            var modern = s_fixture.Value.CreateModern(entityType);
            Assert.Equal(legacy.ReadPrimaryKey(noPkRecord), modern.ReadPrimaryKey(noPkRecord));
            legacy.ReadSelf(noPkRecord);
            modern.ReadSelf(noPkRecord);
            Assert.Equal(Serialize(legacy), Serialize(modern));
        }

        [Fact]
        public void EntityIsCreatedThroughFactoryInterface()
        {
            IEntityFactory factory = s_fixture.Value.Registry;
            var entityType = s_fixture.Value.EntityTypes.First();

            Assert.IsAssignableFrom(entityType, factory.Create(entityType));
            Assert.Null(factory.TryCreate(typeof(IDisposable)));
            Assert.Throws<InvalidOperationException>(() => factory.Create(typeof(IDisposable)));
        }

        private static void AssertReadMatches(Type entityType, FakeDataRecord record)
        {
            var legacy = s_fixture.Value.CreateLegacy(entityType);
            var modern = s_fixture.Value.CreateModern(entityType);

            SetIsDirty(legacy, false);
            SetIsDirty(modern, false);

            Assert.Equal(legacy.ReadPrimaryKey(record), modern.ReadPrimaryKey(record));

            legacy = s_fixture.Value.CreateLegacy(entityType);
            modern = s_fixture.Value.CreateModern(entityType);

            legacy.ReadSelf(record);
            modern.ReadSelf(record);

            Assert.Equal(legacy.IsDirty, modern.IsDirty);
            Assert.Equal(legacy.GetSaveMethodType(), modern.GetSaveMethodType());
            Assert.Equal(Serialize(legacy), Serialize(modern));
            AssertValuesEqual(legacy, modern);
        }

        private static void AssertValuesEqual(IEntity legacy, IEntity modern)
        {
            var legacyValues = legacy.GetValues().ToList();
            var modernValues = modern.GetValues().ToList();

            Assert.Equal(legacyValues.Select(v => $"{v.ColumnName}|{v.IsPk}").ToList(), modernValues.Select(v => $"{v.ColumnName}|{v.IsPk}").ToList());

            for (var i = 0; i < legacyValues.Count; i++)
            {
                Assert.Equal(legacyValues[i].Value, modernValues[i].Value);
            }
        }

        private static List<string> DescribeProperties(Type runtimeType)
        {
            return runtimeType.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                .Select(p => $"{p.Name}:{p.PropertyType.FullName}:get={p.GetGetMethod() != null}:set={p.GetSetMethod() != null}")
                .OrderBy(s => s, StringComparer.Ordinal)
                .ToList();
        }

        private static string Serialize(object entity)
        {
            return JsonConvert.SerializeObject(entity);
        }

        private static void SetIsDirty(IEntity entity, bool value)
        {
            entity.GetType().GetProperty(nameof(IEntity.IsDirty)).SetValue(entity, value);
        }

        private static void Fill(IEntity entity)
        {
            var index = 0;
            foreach (var property in entity.GetType().GetProperties(BindingFlags.Public | BindingFlags.Instance).OrderBy(p => p.Name, StringComparer.Ordinal))
            {
                index++;

                if (s_entityInterfaceMembers.Contains(property.Name) || (property.GetSetMethod() == null))
                {
                    continue;
                }

                var value = SampleValue(property.PropertyType, index);
                if (value != null)
                {
                    property.SetValue(entity, value);
                }
            }
        }

        private static object SampleValue(Type type, int index)
        {
            var t = Nullable.GetUnderlyingType(type) ?? type;

            if (t == typeof(string)) return $"value{index}";
            if (t == typeof(int)) return 1000 + index;
            if (t == typeof(long)) return 100000L + index;
            if (t == typeof(short)) return (short)(100 + index);
            if (t == typeof(byte)) return (byte)(1 + (index % 200));
            if (t == typeof(bool)) return true;
            if (t == typeof(decimal)) return 1.25m + index;
            if (t == typeof(double)) return 2.5d + index;
            if (t == typeof(float)) return 3.5f + index;
            if (t == typeof(DateTime)) return new DateTime(2020, 1, 1, 10, 20, 30).AddDays(index);
            if (t == typeof(TimeSpan)) return TimeSpan.FromMinutes(index + 1);
            if (t == typeof(Guid)) return new Guid(index, 1, 2, new byte[] { 3, 4, 5, 6, 7, 8, 9, 10 });
            if (t == typeof(char)) return (char)('a' + (index % 26));
            if (t == typeof(byte[])) return new byte[] { 1, 2, (byte)index };

            if (t.IsEnum)
            {
                var values = Enum.GetValues(t);
                return values.Length > 0 ? values.GetValue(values.Length - 1) : null;
            }

            return null;
        }

        private sealed class Fixture
        {
            private readonly IServiceLocator _legacyLocator;

            public Fixture()
            {
                EntityTypes = FindEntityTypes().ToList();
                Registry = RobOrmConfiguration.Create().ScanAssemblies(FindAssemblies()).BuildEntityRegistry();
                _legacyLocator = LegacyEntityGenerator.CreateLocator(EntityTypes);
            }

            public List<Type> EntityTypes { get; }

            public EntityRegistry Registry { get; }

            public static IEnumerable<Type> FindEntityTypes()
            {
                return FindAssemblies()
                    .SelectMany(a => a.GetTypes())
                    .Where(t => Attribute.IsDefined(t, typeof(EntityAttribute), false))
                    .OrderBy(t => t.FullName, StringComparer.Ordinal);
            }

            public IEntity CreateLegacy(Type entityType)
            {
                return (IEntity)_legacyLocator.Get(entityType);
            }

            public IEntity CreateModern(Type entityType)
            {
                return (IEntity)Registry.Create(entityType);
            }

            private static IReadOnlyList<Assembly> FindAssemblies()
            {
                return AssemblyDiscovery.FindEntityAssemblies(
                    new[] { typeof(RobOrmEntityGenerationTests).Assembly },
                    n => n.Name.StartsWith("Elsa.", StringComparison.OrdinalIgnoreCase));
            }
        }

        private sealed class FakeDataRecord : IDataRecord
        {
            private readonly Dictionary<string, object> _values;

            public FakeDataRecord(Dictionary<string, object> values)
            {
                _values = values;
            }

            public string RootPath => string.Empty;

            public IDataRecord GetDeeperReader(string pathSegment)
            {
                throw new NotSupportedException();
            }

            public T Get<T>(string columnName)
            {
                object value;
                if (!_values.TryGetValue(columnName, out value) || (value == null))
                {
                    return default(T);
                }

                return (T)value;
            }

            public T Get<T>(int columnOrdinal)
            {
                throw new NotSupportedException();
            }

            public bool IsNull(string columnName)
            {
                object value;
                return !_values.TryGetValue(columnName, out value) || (value == null);
            }
        }
    }
}
